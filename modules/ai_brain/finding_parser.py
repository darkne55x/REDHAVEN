#!/usr/bin/env python3
"""
REDHAVEN AI — Universal Finding Parser
========================================
Parses all output files generated by RedHaven modules into a structured
format that the AI brain can analyze.

Supported file types:
    - Text files (one finding per line)
    - JSON files (structured data)
    - Nuclei JSONL output
    - httpx probe results

Usage:
    from ai_brain.finding_parser import FindingParser
    parser = FindingParser("/results/target.com")
    findings = parser.parse_all()
"""

import json
import os
import re
from pathlib import Path
from typing import Dict, List, Any, Optional
from dataclasses import dataclass, field


# ============================================================================
# Data Structures
# ============================================================================

@dataclass
class Finding:
    """A single security finding from any module."""
    category: str          # e.g., "xss", "ssrf", "secrets"
    severity: str          # CRITICAL, HIGH, MEDIUM, LOW, INFO
    source_file: str       # Which file it came from
    raw_data: str          # Raw line/entry
    url: str = ""          # Target URL if applicable
    parameter: str = ""    # Affected parameter
    details: Dict = field(default_factory=dict)  # Extra context


@dataclass
class ScanResults:
    """Aggregated results from all RedHaven modules."""
    target: str
    target_dir: str

    # Recon
    subdomains: List[str] = field(default_factory=list)
    alive_urls: List[str] = field(default_factory=list)
    endpoints: List[str] = field(default_factory=list)
    parameters: List[str] = field(default_factory=list)
    technologies: List[str] = field(default_factory=list)

    # Vulnerabilities
    findings: List[Finding] = field(default_factory=list)

    # Metadata
    scan_files_found: List[str] = field(default_factory=list)
    scan_files_empty: List[str] = field(default_factory=list)

    def get_by_category(self, category: str) -> List[Finding]:
        return [f for f in self.findings if f.category == category]

    def get_by_severity(self, severity: str) -> List[Finding]:
        return [f for f in self.findings if f.severity == severity]

    @property
    def critical_count(self) -> int:
        return len(self.get_by_severity("CRITICAL"))

    @property
    def high_count(self) -> int:
        return len(self.get_by_severity("HIGH"))

    @property
    def categories(self) -> List[str]:
        return sorted(set(f.category for f in self.findings))

    def summary_dict(self) -> Dict[str, Any]:
        """Compact summary suitable for LLM prompts."""
        cat_counts = {}
        for f in self.findings:
            key = f"{f.category} ({f.severity})"
            cat_counts[key] = cat_counts.get(key, 0) + 1

        return {
            "target": self.target,
            "subdomains_count": len(self.subdomains),
            "alive_urls_count": len(self.alive_urls),
            "endpoints_count": len(self.endpoints),
            "parameters_count": len(self.parameters),
            "tech_stack": self.technologies[:20],
            "total_findings": len(self.findings),
            "critical": self.critical_count,
            "high": self.high_count,
            "findings_by_category": cat_counts,
            "categories": self.categories,
        }


