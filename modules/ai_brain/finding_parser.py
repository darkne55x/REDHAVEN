    import sys

    if len(sys.argv) < 2:
        print("Usage: finding_parser.py <target_directory>")
        sys.exit(1)

    parser = FindingParser(sys.argv[1])
    results = parser.parse_all()

    print(f"\n{'='*60}")
    print(f"REDHAVEN AI — Finding Parser Results")
    print(f"{'='*60}")

    summary = results.summary_dict()
    for k, v in summary.items():
        print(f"  {k}: {v}")

    print(f"\nFiles parsed: {len(results.scan_files_found)}")
    print(f"Files empty: {len(results.scan_files_empty)}")
    print(f"\n{'='*60}")
    print("PROMPT CONTEXT PREVIEW:")
    print(f"{'='*60}")
    print(parser.to_prompt_context(results, max_items=5))
